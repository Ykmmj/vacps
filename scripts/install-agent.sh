install_nvm_node() {
  install -d -m 755 "$NVM_DIR"
  if [[ ! -s $NVM_DIR/nvm.sh ]]; then
    echo 'Installing NVM 0.40.6...'
    NVM_DIR="$NVM_DIR" PROFILE=/dev/null bash -c \
      'curl --fail --silent --show-error --location https://raw.githubusercontent.com/nvm-sh/nvm/v0.40.6/install.sh | bash'
  fi
  # shellcheck disable=SC1090
  . "$NVM_DIR/nvm.sh"
  nvm install "$NODE_MAJOR_VERSION"
  nvm alias default "$NODE_MAJOR_VERSION"
  nvm use "$NODE_MAJOR_VERSION"
  if ! command -v corepack >/dev/null; then
    echo 'The NVM-installed Node.js runtime does not provide Corepack.' >&2
    exit 1
  fi
  corepack enable pnpm
}

b64url_encode() {
  openssl base64 -A | tr '+/' '-_' | tr -d '='
}

generate_agent_identity_openssl() {
  local dir
  dir=$(mktemp -d)
  openssl genpkey -algorithm ED25519 -out "$dir/key.pem" >/dev/null 2>&1
  AGENT_PRIVATE_KEY=$(openssl pkey -in "$dir/key.pem" -outform DER 2>/dev/null | b64url_encode)
  # Ed25519 SPKI DER ends with 0x00 0x20 + 32-byte raw public key.
  AGENT_PUBLIC_KEY=$(openssl pkey -in "$dir/key.pem" -pubout -outform DER 2>/dev/null | tail -c 32 | b64url_encode)
  rm -rf "$dir"
}

generate_agent_identity() {
  local identity
  if command -v node >/dev/null 2>&1; then
    identity=$(node --input-type=module -e '
      const pair = await crypto.subtle.generateKey({ name: "Ed25519" }, true, ["sign", "verify"]);
      const privateKey = Buffer.from(await crypto.subtle.exportKey("pkcs8", pair.privateKey)).toString("base64url");
      const publicKey = Buffer.from(await crypto.subtle.exportKey("raw", pair.publicKey)).toString("base64url");
      process.stdout.write(`${privateKey} ${publicKey}`);
    ')
    AGENT_PRIVATE_KEY=${identity%% *}
    AGENT_PUBLIC_KEY=${identity##* }
  else
    generate_agent_identity_openssl
  fi
  if [[ ! $AGENT_PRIVATE_KEY =~ ^[A-Za-z0-9_-]{64,256}$ || ! $AGENT_PUBLIC_KEY =~ ^[A-Za-z0-9_-]{43}$ ]]; then
    echo 'Could not generate a local Ed25519 Agent identity.' >&2
    exit 1
  fi
}

detect_installed_runtime() {
  if [[ -f $RUNTIME_MARKER_FILE ]]; then
    tr -d '[:space:]' <"$RUNTIME_MARKER_FILE"
    return 0
  fi
  if [[ -f $ENVIRONMENT_FILE ]] && grep -q '^AGENT_RUNTIME=native' "$ENVIRONMENT_FILE"; then
    echo native
    return 0
  fi
  if [[ -x $NATIVE_INSTALL_DIR/$NATIVE_BIN_NAME && -f $NATIVE_INSTALL_DIR/$NATIVE_SCRIPT_NAME ]]; then
    echo native
    return 0
  fi
  echo node
}

is_native_runtime() {
  [[ $AGENT_RUNTIME == native ]]
}

